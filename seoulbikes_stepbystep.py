"""Perform imputation via interpolation of data in Rented Bike Count for any non functioning day. For any non functioning instance/hour we will find the exact hour of last day (idx - 24), exact hour of next day (idx + 24) while skipping consecutive non functioning days.
Its a fact that:
First 24 instances are functioning
The non functioning instances are 295/8760 - 3%
Only non functioning days presented 0 rented bikes

Its possible that:
There are consecutive days without functioning
There is no next day of a non functioning day (End of data)
There could be a small anomalie with interpolation

Therefore we can create and index, find the non functioning instance, finde the corresponding value before and after, calculate the interpolation and impute.

"""

# Imputation function

def imput(df):

    df_im = df.copy()
    index_fund = df_im[df_im['Functioning Day'] == 0].index

    for idx in index_fund:

        before = 24
        while (idx - before >= 0) and (df_im.loc[idx - before, 'Functioning Day'] == 0):
            before += 24

        next_step = 24
        while (idx + next_step < len(df_im)) and (df_im.loc[idx + next_step, 'Functioning Day'] == 0):
            next_step += 24

        b_val = df_im.loc[idx - before, 'Rented Bike Count'] if (idx - before >= 0) else np.nan
        n_val = df_im.loc[idx + next_step, 'Rented Bike Count'] if (idx + next_step < len(df_im)) else np.nan

        # Interpolation
        if pd.notna(b_val) and pd.notna(n_val):
            imputation = (b_val + n_val) / 2
        elif pd.notna(b_val):
            imputation = b_val
        elif pd.notna(n_val):
            imputation = n_val

        # Imputation
        df_im.loc[idx, 'Rented Bike Count'] = imputation

    return df_im

"""Impute and Check for correct imputation and type."""

