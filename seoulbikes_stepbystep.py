"""Division of classes X_train, Y_train, X_test and Y_Test.
The test will represent aproximately 10% of data.

X_test, Y_test --> last 216 instances of each season.
X_train, Y_train --> remaining block of instances.
For dividing each chunk we will locate the position of season change and create arrange with the corresponding start and end of each season. We will append each chunk for each season with the located index values and train gets the chunk -216 and test the last 216 instances.
"""

df['instance_id'] = df.index

